    "# Cell 6: POI Lookup + LLM Location Naming\n",
    "def get_nearby_pois(lat, lon, radius_m=500):\n",
    "    \"\"\"\n",
    "    Query Overpass API for named places near a coordinate.\n",
    "    Includes node + way + relation (university buildings are often relations).\n",
