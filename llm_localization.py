    "        for i, (_, row) in enumerate(sample.iterrows()):\n",
    "            plat, plon = add_gps_noise(row['lat'], row['lon'], noise)\n",
    "            pois = get_nearby_pois(plat, plon, radius_m=max(300, noise))\n",
